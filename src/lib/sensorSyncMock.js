export function computeSyncSummary(data) {
  const received = data.length
  const integrated = data.filter((item) => item.status === 'valid').length
  const errors = data.filter((item) => item.status === 'error').length
  const rejected = data.filter((item) => item.status === 'rejected').length

  return {
    received,
    integrated,
    errors,
    rejected,
  }
}
